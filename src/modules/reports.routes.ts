import { Router } from 'express';
import { authenticate } from '../middleware/authentication.js';
import { instituteOwnership } from '../middleware/institute-ownership.js';
import { requirePermission, requireRole } from '../middleware/authorization.js';
import { ROLES } from '../types/rbac.js';
import { asyncHandler } from '../utils/async-handler.js';
import { reportsController as c } from './reports.controller.js';
export const reportsRouter = Router();
reportsRouter.use(authenticate, instituteOwnership(), requireRole(...ROLES), requirePermission('report.view'));
reportsRouter.get('/dashboard', asyncHandler(c.dashboard));
reportsRouter.get('/revenue', asyncHandler(c.revenue));
reportsRouter.get('/expenses', asyncHandler(c.expenses));
reportsRouter.get('/pnl', asyncHandler(c.pnl));
reportsRouter.get('/cash-flow', asyncHandler(c.cashFlow));
reportsRouter.get('/course-profitability', asyncHandler(c.courseProfitability));
reportsRouter.get('/course-profitability/policy', asyncHandler(c.profitabilityPolicy));
reportsRouter.put('/course-profitability/policy', requirePermission('course_profitability.manage'), asyncHandler(c.updateProfitabilityPolicy));
reportsRouter.get('/course-profitability/allocations', asyncHandler(c.courseCostAllocations));
reportsRouter.post('/course-profitability/allocations', requirePermission('course_profitability.manage'), asyncHandler(c.allocateCourseCost));
reportsRouter.get('/crm', asyncHandler(c.crm));
reportsRouter.get('/admissions', asyncHandler(c.admissions));
reportsRouter.get('/students', asyncHandler(c.students));
reportsRouter.get('/attendance', asyncHandler(c.attendance));
reportsRouter.get('/staff', asyncHandler(c.staff));
